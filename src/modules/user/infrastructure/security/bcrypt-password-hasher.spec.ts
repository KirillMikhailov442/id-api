import { BcryptPasswordHasher } from "@modules/user/infrastructure/security/bcrypt-password-hasher";

describe("BcryptPasswordHasher", () => {
  const service = new BcryptPasswordHasher();

  it("salts hashes independently and verifies each with the original password", async () => {
    const password = "S3cure!Password";
    const first = await service.hash(password);
    const second = await service.hash(password);
    expect(first).toMatch(/^\$2[aby]\$10\$[./A-Za-z0-9]{53}$/);
    expect(first).not.toBe(second);
    expect(first).not.toBe(password);
    await expect(service.compare(password, first)).resolves.toBe(true);
    await expect(service.compare(password, second)).resolves.toBe(true);
  });

  it("verifies a bcrypt test vector generated by Apache htpasswd", async () => {
    await expect(
      service.compare("password", "$2b$10$Cd04SDRtZnS6iZ42NKOpieE199Nn0vN8oHsopnAOdYnAxDXl/Iuua")
    ).resolves.toBe(true);
  });

  it("rejects incorrect passwords without trimming or changing case", async () => {
    const hash = await service.hash("S3cure!Password");

    for (const password of ["wrong", "s3cure!Password", " S3cure!Password", "S3cure!Password ", ""]) {
      await expect(service.compare(password, hash)).resolves.toBe(false);
    }
  });

  it.each(["", "not-a-bcrypt-hash", "$2b$10$short"])("rejects malformed stored hashes %p", async (hash) => {
    await expect(service.compare("S3cure!Password", hash)).resolves.toBe(false);
  });
});
